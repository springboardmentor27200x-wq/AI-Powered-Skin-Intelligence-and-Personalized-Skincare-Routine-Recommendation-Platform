def seed_genuine_datasets(db: Session) -> Dict[str, int]:
    """Idempotently seeds canonical ingredients, interaction safeguards, and authentic products."""
    created_ingredients = 0
    created_products = 0

    # 1. Ingest Canonical Ingredients
    ing_map = {}
    for ing_data in GENUINE_INGREDIENTS:
        existing = db.query(Ingredient).filter(
            (Ingredient.name == ing_data["name"]) |
            (Ingredient.normalized_name == ing_data["normalized_name"])
        ).first()

        if not existing:
            ingredient = Ingredient(
                id=uuid.uuid4(),
                name=ing_data["name"],
                normalized_name=ing_data["normalized_name"],
                category=ing_data["category"],
                description=ing_data["description"],
                common_uses=ing_data["common_uses"],
                suitability_notes=ing_data["suitability_notes"],
                caution_notes=ing_data["caution_notes"],
                education_content=ing_data["education_content"],
                aliases=ing_data["aliases"],
                suitable_for=ing_data["suitable_for"],
                caution_for=ing_data["caution_for"],
                avoid_for=ing_data["avoid_for"],
                target_concerns=ing_data["target_concerns"],
                is_active=True,
            )
            db.add(ingredient)
            db.flush()
            ing_map[ing_data["normalized_name"]] = ingredient
            created_ingredients += 1
        else:
            ing_map[ing_data["normalized_name"]] = existing

    # 2. Ingest Clinical Ingredient Interactions
    def link_interaction(norm_a: str, norm_b: str, itype: str, sev: str, rec: str, desc: str):
        ia = ing_map.get(norm_a) or db.query(Ingredient).filter(Ingredient.normalized_name == norm_a).first()
        ib = ing_map.get(norm_b) or db.query(Ingredient).filter(Ingredient.normalized_name == norm_b).first()
        if ia and ib and ia.id != ib.id:
            existing_int = db.query(IngredientInteraction).filter(
                ((IngredientInteraction.ingredient_a_id == ia.id) & (IngredientInteraction.ingredient_b_id == ib.id)) |
                ((IngredientInteraction.ingredient_a_id == ib.id) & (IngredientInteraction.ingredient_b_id == ia.id))
            ).first()
            if not existing_int:
                inter = IngredientInteraction(
                    id=uuid.uuid4(),
                    ingredient_a_id=ia.id,
                    ingredient_b_id=ib.id,
                    interaction_type=itype,
                    severity=sev,
                    recommendation=rec,
                    description=desc,
                )
                db.add(inter)

    link_interaction(
        "retinol", "glycolic acid", "AVOID", "HIGH",
        "Do not apply Retinol and Glycolic Acid in the same application. Using strong AHAs concurrently with retinoids degrades barrier integrity and causes severe dermatitis.",
        "Concurrent use leads to excessive stratum corneum desquamation and barrier compromise."
    )
    link_interaction(
        "retinol", "salicylic acid", "SEPARATE", "MODERATE",
        "Separate use: apply Salicylic Acid in the morning (or on alternate evenings) and Retinol in the evening to prevent severe dryness and peeling.",
        "Overlapping keratolytic action may trigger significant trans-epidermal moisture loss."
    )
    link_interaction(
        "retinol", "benzoyl peroxide", "SEPARATE", "HIGH",
        "Separate use: Benzoyl Peroxide oxidizes tretinoin/retinol molecules, neutralizing their anti-aging efficacy while causing intense irritation.",
        "Oxidative degradation of retinoid molecules."
    )
    link_interaction(
        "hyaluronic acid", "ceramides", "SYNERGY", "LOW",
        "Excellent synergistic combination. Hyaluronic acid draws moisture in, while ceramides seal the barrier to prevent water loss.",
        "Humectant-lipid synergy produces superior stratum corneum hydration."
    )
    link_interaction(
        "niacinamide", "ceramides", "SYNERGY", "LOW",
        "Highly beneficial pairing. Niacinamide stimulates natural ceramide synthesis while topical ceramides immediately repair the lipid barrier.",
        "Complementary barrier reinforcement pathways."
    )
    link_interaction(
        "centella asiatica", "retinol", "SYNERGY", "LOW",
        "Exceptional pairing. Centella Asiatica actively calms the redness and irritation commonly experienced during retinization.",
        "Centelloside triterpenes counteract retinoid-induced epidermal inflammation."
    )
    link_interaction(
        "salicylic acid", "niacinamide", "SYNERGY", "LOW",
        "Effective duo. Salicylic Acid clears inside the pore lining while Niacinamide regulates sebum production and refines surface pores.",
        "Complementary follicular clearing and sebostatic regulation."
    )

    # 3. Ingest Genuine Products
    for p_data in GENUINE_PRODUCTS:
        existing = db.query(Product).filter(
            Product.name == p_data["name"],
            Product.brand == p_data["brand"],
        ).first()

        if not existing:
            product = Product(
                id=uuid.uuid4(),
                name=p_data["name"],
                brand=p_data["brand"],
                category=p_data["category"],
                description=p_data["description"],
                price=p_data["price"],
                currency=p_data["currency"],
                size=p_data["size"],
                ingredients=p_data["ingredients"],
                active_ingredients=p_data["active_ingredients"],
                skin_types=p_data["skin_types"],
                target_concerns=p_data["target_concerns"],
                sensitivity_flags=p_data["sensitivity_flags"],
                budget_band=p_data["budget_band"],
                is_available=True,
                is_seed_data=True,
            )
            db.add(product)
            created_products += 1

    db.commit()
    print(f"Ingested {created_ingredients} genuine ingredients and {created_products} genuine products.")
    return {"ingredients": created_ingredients, "products": created_products}


